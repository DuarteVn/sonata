//! Agent helpers for zsh terminals: `claude` and `codex` typed by hand start through
//! `sonata run`, so they get Sonata's session instructions. The user's startup files are loaded
//! as usual and never changed; Sonata only points `ZDOTDIR` at its own small files that source
//! them first.

use std::io;
use std::path::Path;

use crate::paths::ensure_private_dir;
use crate::persistence::atomic;

/// Each file loads the user's file of the same name with the user's `ZDOTDIR`, then switches
/// back so zsh keeps reading Sonata's files. `.zshrc` restores the user's `ZDOTDIR` at the end,
/// so `.zlogin` and nested shells behave as usual.
const LOAD_USER: &str = r#"_sonata_dir=$ZDOTDIR
ZDOTDIR=${SONATA_USER_ZDOTDIR:-$HOME}
[[ -r $ZDOTDIR/FILE ]] && builtin source $ZDOTDIR/FILE
SONATA_USER_ZDOTDIR=$ZDOTDIR
ZDOTDIR=$_sonata_dir
"#;

const HELPERS: &str = r#"
# Sonata: agents typed by hand get Sonata's session instructions.
if (( $+commands[sonata] )); then
  claude() { command sonata run claude "$@" }
  codex() { command sonata run codex "$@" }
fi
ZDOTDIR=$SONATA_USER_ZDOTDIR
unset _sonata_dir
"#;

pub fn write_files(dir: &Path) -> io::Result<()> {
    ensure_private_dir(dir)?;
    for name in [".zshenv", ".zprofile", ".zshrc"] {
        let mut body = format!(
            "# Generated by Sonata. Loads your own {name}.\n{}",
            LOAD_USER.replace("FILE", name)
        );
        if name == ".zshrc" {
            body.push_str(HELPERS);
        }
        atomic::write(&dir.join(name), body.as_bytes())?;
    }
    Ok(())
}
