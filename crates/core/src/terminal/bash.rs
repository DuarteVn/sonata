//! Agent helpers for bash terminals (feature 011, research R8): `claude` and `codex` typed by
//! hand start through `sonata run`. bash runs with `--rcfile` pointing here, so this file first
//! repeats what a login bash reads (`/etc/profile`, then the first of the user's
//! `~/.bash_profile`, `~/.bash_login`, `~/.profile`). The user's files are never changed.

use std::io;
use std::path::Path;

use crate::paths::ensure_private_dir;
use crate::persistence::atomic;

pub const BASHRC: &str = r#"# Generated by Sonata. Loads your login startup files, then adds Sonata's agent helpers.
[ -r /etc/profile ] && builtin source /etc/profile
for _sonata_file in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
  if [ -r "$_sonata_file" ]; then
    builtin source "$_sonata_file"
    break
  fi
done
unset _sonata_file

# Sonata: agents typed by hand get Sonata's session instructions.
if command -v sonata >/dev/null 2>&1; then
  claude() { command sonata run claude "$@"; }
  codex() { command sonata run codex "$@"; }
fi
"#;

pub fn write_files(dir: &Path) -> io::Result<()> {
    ensure_private_dir(dir)?;
    atomic::write(&dir.join("bashrc"), BASHRC.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::BASHRC;

    fn at(needle: &str) -> usize {
        BASHRC
            .find(needle)
            .unwrap_or_else(|| panic!("missing {needle}"))
    }

    #[test]
    fn login_files_load_in_bash_order_before_the_helpers() {
        assert!(at("/etc/profile") < at(".bash_profile"));
        assert!(at(".bash_profile") < at(".bash_login"));
        assert!(at(".bash_login") < at("$HOME/.profile"));
        assert!(at("break") < at("claude()"));
    }

    #[test]
    fn helpers_exist_only_when_the_cli_is_on_path() {
        assert!(at("command -v sonata") < at("claude()"));
        assert!(BASHRC.contains(r#"claude() { command sonata run claude "$@"; }"#));
        assert!(BASHRC.contains(r#"codex() { command sonata run codex "$@"; }"#));
    }
}
